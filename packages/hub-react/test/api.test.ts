describe('what is marked @experimental', () => {
  // 0.2.0 settled the embedding API: nothing in either package is tagged any more (the three outside adapters that still are live in @chatwarden/http).
  it('no export, and no member of an export, is marked @experimental in hub-react, its headless entry or player-react', () => {
    for (const [label, entry] of [['hub-react', HUB], ['hub-react/headless', HEADLESS], ['player-react', PLAYER]] as const) {
      const found = exportsOf(entry);
      expect(found.experimental, label).toEqual([]);
      expect(found.experimentalMembers, label).toEqual([]);
    }
  });

  it('control: the scan still sees the exports it judges, and the members the lock would flag', () => {
    expect(exportsOf(HUB).values).toContain('Hub');
    expect(exportsOf(HUB).values).toContain('useHubController');
    expect(exportsOf(HEADLESS).values.length).toBeGreaterThan(20);
    expect(exportsOf(PLAYER).values).toContain('ReportDialog');
  });
});

describe('the lock itself', () => {
  it('a name that is not exported is not in the list (control), and a type-only export is a type, not a value', () => {
    const hub = exportsOf(HUB);
    expect(hub.values).not.toContain('NotExportedAnywhere');
    expect(hub.values).not.toContain('HubClient');
    expect(hub.types).toContain('HubClient');
    expect(hub.types).not.toContain('Hub');
  });
});
