// `cw.legal` (0.2.0, design section 6): hold and release a report, and the evidence bundle. The data shapes and the closed code list are in legal.ts; the rows a hold
// protects are the store's to keep (its purges and the erase read its holds themselves). Nothing here reads chat text except the bundle's own excerpt.

import { BUNDLE_SECRET_MIN, signBundle } from './canonical.js';
import type { BundleIntegrity } from './canonical.js';
import { isValidAuditActor } from './audit.js';
import { isHoldCode } from './legal.js';
import type { HoldCode } from './legal.js';
import { isNonPersonReporter } from './privacy.js';
import type { KitEvent, StaffRef } from './events.js';
import type { Clock, Store, SubjectId } from './types.js';

/** What the bundle says about itself. The words are fixed (a test pins them). */
export const BUNDLE_DISCLAIMER =
  'Generated by Chatwarden. It records what the kit held. It does not say whether any content is unlawful and is not legal advice.';

/** One person of a bundle: an index the other parts point at, a staff ref and the handle the report kept; account ids only when asked for. */
export interface BundlePerson {
  index: number;
  ref: StaffRef;
  /** The handle kept with the report (or with the line), never a current name. */
  handle: string;
  role: 'reporter' | 'target' | 'speaker' | 'other';
  /** Only with `includeAccounts`: the account ids as the game gave them. */
  accounts?: string[];
}

/**
 * The evidence bundle of one report (`cw.legal.bundle`). No hash, raw key, address or other player's id outside `people`; no free text of staff beyond the report's own
 * note, the sanction reasons and the appeal statements. `integrity` signs everything (see `verifyBundle`).
 * @experimental
 */
export interface EvidenceBundle {
  format: 'chatwarden.evidence-bundle';
  version: 1;
  generatedAt: number;
  kit: { name: '@chatwarden/core'; version: string };
  disclaimer: string;
  report: {
    id: string;
    createdAt: number;
    roomTags: Record<string, string>;
    category: string;
    reason: string | null;
    note: string | null;
    status: string;
    decidedAt: number | null;
    origin: string | null;
  };
  people: BundlePerson[];
  excerpt: Array<{ lineId: string; ts: number; p: number | null; raw: string; delivered: string | null; blocked: boolean }>;
  decisions: Array<{ at: number; by: string; outcome: 'actioned' | 'dismissed'; badFaith: boolean }>;
  sanctions: Array<{
    p: number | null;
    kind: string;
    rule: string | null;
    reason: string;
    startsAt: number;
    endsAt: number | null;
    refCode: string;
    by: string;
    revoked: { at: number; by: string } | null;
  }>;
  notices: Array<{ p: number | null; kind: string; createdAt: number; ackedAt: number | null; withdrawnAt: number | null }>;
  appeals: Array<{ p: number | null; status: string; createdAt: number; decidedAt: number | null; statement: string | null }>;
  audit: Array<{ at: number; actor: string; role: string | null; action: string; target: { type: string; ref: string } | null }>;
  hold: { code: HoldCode; at: number; releasedAt: number | null } | null;
  integrity: BundleIntegrity;
}

/** What `hold` answers. @experimental */
export type HoldResult = { ok: true } | { ok: false; error: 'not_found' | 'already_held' | 'invalid' };

/** `cw.legal`. @experimental */
export interface LegalService {
  /** Hold a report so no purge and no erase reaches it, for a code on the closed list. A senior's in the HTTP layer; here any actor string. */
  hold(reportId: string, input: { code: HoldCode; actor: string }): Promise<HoldResult>;
  /** Release a hold. `{ ok: false }` when the report was not held. The owner's in the HTTP layer. */
  release(reportId: string, input: { actor: string }): Promise<{ ok: boolean }>;
  /** The open hold of a report, for its staff body: the code and the time, never who. */
  status(reportId: string): { code: HoldCode; at: number } | null;
  /** The evidence bundle of a report, signed with `bundleSecret` when the kit has one. The owner's in the HTTP layer. */
  bundle(reportId: string, input: { actor: string; includeAccounts?: boolean }): Promise<EvidenceBundle | { ok: false; error: 'not_found' }>;
}

export interface LegalDeps {
  store: Store;
  clock: Clock;
  /** Announces `report.escalated` (the facade's bus). Fenced there. */
  emit: (event: Extract<KitEvent, { type: 'report.escalated' }>) => void;
  canonical: (subject: SubjectId) => SubjectId;
  accountIds: (subject: SubjectId) => string[];
  /** At least 32 characters, or undefined (bundles are then produced unsigned). Never logged. */
  bundleSecret: string | undefined;
  kitVersion: string;
}

/** The longest a bundle's audit section reads: five pages of 200. */
const AUDIT_PAGES = 5;

/** Check the option at creation. Names the option, never the value. */
export function checkBundleSecret(secret: unknown): string | undefined {
  if (secret === undefined) return undefined;
  if (typeof secret !== 'string' || secret.length < BUNDLE_SECRET_MIN) {
    throw new RangeError(`createChatwarden: bundleSecret must be a string of at least ${BUNDLE_SECRET_MIN} characters`);
  }
  return secret;
}

export function createLegal(deps: LegalDeps): LegalService {
  const { store, clock } = deps;

  const status = (reportId: string): { code: HoldCode; at: number } | null => {
    const row = typeof reportId === 'string' ? store.transaction(() => store.loadHold(reportId)) : null;
    return row === null || row.releasedAt !== null ? null : { code: row.code, at: row.heldAt };
  };

  return {
    status,

    hold: (reportId, input) => {
      try {
        if (typeof reportId !== 'string' || reportId === '' || !isHoldCode(input?.code) || !isValidAuditActor(input?.actor)) return Promise.resolve({ ok: false, error: 'invalid' });
        const at = clock.now();
        const out = store.transaction((): { error: 'not_found' | 'already_held' } | { target: SubjectId } => {
          const report = store.loadReport(reportId);
          if (report === null) return { error: 'not_found' };
          const placed = store.placeHold({ reportId, code: input.code, heldBy: input.actor, heldAt: at, releasedBy: null, releasedAt: null });
          return placed ? { target: report.targetSubject } : { error: 'already_held' };
        });
        if ('error' in out) return Promise.resolve({ ok: false, error: out.error });
        // After the commit: the event carries ids and a code only, and a listener that throws cannot undo the hold (the bus fences it).
        deps.emit({ type: 'report.escalated', reportId, at, code: input.code, target: deps.canonical(out.target) });
        return Promise.resolve({ ok: true });
      } catch (err) {
        return Promise.reject(err);
      }
    },

    release: (reportId, input) => {
      try {
        if (typeof reportId !== 'string' || !isValidAuditActor(input?.actor)) return Promise.resolve({ ok: false });
        return Promise.resolve({ ok: store.transaction(() => store.releaseHold(reportId, input.actor, clock.now())) });
      } catch (err) {
        return Promise.reject(err);
      }
    },

    bundle: (reportId, input) => {
      try {
        if (!isValidAuditActor(input?.actor)) throw new TypeError('legal.bundle: actor must be a staff ref');
        return Promise.resolve(buildBundle(deps, reportId, input.includeAccounts === true));
      } catch (err) {
        return Promise.reject(err);
      }
    },
  };
}

function buildBundle(deps: LegalDeps, reportId: string, includeAccounts: boolean): EvidenceBundle | { ok: false; error: 'not_found' } {
  const { store, clock } = deps;
  return store.transaction(() => {
    const report = typeof reportId === 'string' ? store.loadReport(reportId) : null;
    if (report === null) return { ok: false, error: 'not_found' } as const;

    // The people index: the reporter (when a person filed it), the target, then every other writer, then anyone a sanction names. A merged alias is one person.
    const people: BundlePerson[] = [];
    const indexOf = new Map<SubjectId, number>();
    const add = (subject: SubjectId, handle: string, role: BundlePerson['role']): number => {
      const ref = deps.canonical(subject);
      const known = indexOf.get(ref);
      if (known !== undefined) return known;
      const person: BundlePerson = { index: people.length, ref, handle, role };
      if (includeAccounts) person.accounts = [...deps.accountIds(ref)].sort();
      people.push(person);
      indexOf.set(ref, person.index);
      return person.index;
    };
    if (!isNonPersonReporter(report.reporterSubject)) add(report.reporterSubject, report.reporterHandle, 'reporter');
    add(report.targetSubject, report.targetHandle, 'target');
    const lineOf = (i: number): number | null => {
      const subject = report.people[i];
      if (subject === undefined || isNonPersonReporter(subject)) return null;
      const first = report.excerpt.find((l) => l.p === i);
      return add(subject, first?.handle ?? '', 'speaker');
    };
    const excerpt = report.excerpt.map((l) => ({
      lineId: l.lineId,
      ts: l.ts,
      p: l.p === null ? null : lineOf(l.p),
      raw: l.raw,
      delivered: l.delivered,
      blocked: l.blocked,
    }));

    const groupIds = store.sanctionGroupsOfReport(reportId);
    const sanctions: EvidenceBundle['sanctions'] = [];
    const notices: EvidenceBundle['notices'] = [];
    const appeals: EvidenceBundle['appeals'] = [];
    for (const groupId of groupIds) {
      const row = store.listSubjectSanctions({ groupId, limit: 1 })[0];
      if (row === undefined) continue;
      const p = add(row.value, '', 'other');
      sanctions.push({
        p,
        kind: row.kind,
        rule: row.rule,
        reason: row.reason,
        startsAt: row.startsAt,
        endsAt: row.endsAt,
        refCode: row.refCode,
        by: row.actor,
        revoked: row.revokedAt == null ? null : { at: row.revokedAt, by: row.revokedBy ?? '' },
      });
      const canonical = deps.canonical(row.value);
      const aliases = canonical === row.value ? [row.value] : [row.value, canonical];
      for (const n of store.loadNotices(aliases)) {
        if (n.groupId === groupId) notices.push({ p, kind: n.kind, createdAt: n.createdAt, ackedAt: n.ackedAt, withdrawnAt: n.withdrawnAt });
      }
      for (const a of store.listAppealsBy?.(aliases, 200) ?? []) {
        if (a.groupId === groupId) appeals.push({ p, status: a.status, createdAt: a.createdAt, decidedAt: a.decidedAt, statement: a.statement });
      }
    }

    const targets = [{ type: 'report' as const, ref: reportId }, ...groupIds.map((g) => ({ type: 'sanction' as const, ref: g }))].slice(0, 20);
    const audit: EvidenceBundle['audit'] = [];
    let before: { at: number; id: string } | undefined;
    for (let page = 0; page < AUDIT_PAGES; page++) {
      const rows = store.listAudit({ limit: 200, targets, ...(before === undefined ? {} : { before: before.at, beforeId: before.id }) });
      for (const r of rows) audit.push({ at: r.at, actor: r.actor, role: r.role, action: r.action, target: r.target === null ? null : { type: r.target.type, ref: r.target.ref } });
      const last = rows.at(-1);
      if (rows.length < 200 || last === undefined) break;
      before = { at: last.at, id: last.id };
    }
    audit.reverse();

    const hold = store.loadHold(reportId);
    const now = clock.now();
    const draft: EvidenceBundle = {
      format: 'chatwarden.evidence-bundle',
      version: 1,
      generatedAt: now,
      kit: { name: '@chatwarden/core', version: deps.kitVersion },
      disclaimer: BUNDLE_DISCLAIMER,
      report: {
        id: report.id,
        createdAt: report.createdAt,
        roomTags: { ...report.tags },
        category: report.category,
        reason: report.reportedReason ?? null,
        note: report.note,
        status: report.status,
        decidedAt: report.actionedAt,
        origin: report.origin,
      },
      people,
      excerpt,
      decisions: report.status === 'open' || report.actionedAt === null ? [] : [{ at: report.actionedAt, by: report.actionedBy ?? '', outcome: report.status, badFaith: report.badFaith }],
      sanctions,
      notices,
      appeals,
      audit,
      hold: hold === null ? null : { code: hold.code, at: hold.heldAt, releasedAt: hold.releasedAt },
      integrity: { algorithm: 'sha256', sha256: '', hmacSha256: null, signedAt: now, canonicalization: 'chatwarden-json-1' },
    };
    return signBundle(draft, deps.bundleSecret, now);
  });
}
