import { describe, expect, it } from 'vitest';
import { BUNDLE_DISCLAIMER } from '../src/legalService.js';
import type { EvidenceBundle } from '../src/legalService.js';
import { canonicalJson, verifyBundle } from '../src/canonical.js';
import { DAY, NOW, P, appealRow, legalWorld, seedFullReport } from './legalWorld.js';

// The evidence bundle (design section 6): what it holds, what it never holds, that it verifies, and that one changed byte fails it.

const OWNER = 'owner_ann';
const SECRET = 'golden-secret-golden-secret-golden-32';

const bundleOf = async (w: Awaited<ReturnType<typeof legalWorld>>, id: string, includeAccounts?: boolean): Promise<EvidenceBundle> => {
  const out = await w.cw.legal.bundle(id, { actor: OWNER, ...(includeAccounts === undefined ? {} : { includeAccounts }) });
  if ('ok' in out) throw new Error('expected a bundle');
  return out;
};

describe('bundle: the report, its people, lines, decision, sanctions, notices, appeals, audit and hold', () => {
  it('holds each part the design lists, with the fixed disclaimer, the kit name and the format', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    await w.cw.legal.hold('r1', { code: 'legal_proceeding', actor: 'senior_gus' });
    const b = await bundleOf(w, 'r1');
    expect(b.format).toBe('chatwarden.evidence-bundle');
    expect(b.version).toBe(1);
    expect(b.generatedAt).toBe(NOW);
    expect(b.kit.name).toBe('@chatwarden/core');
    expect(b.kit.version).toMatch(/^\d+\.\d+\.\d+/);
    expect(b.disclaimer).toBe(BUNDLE_DISCLAIMER);
    expect(BUNDLE_DISCLAIMER).toBe('Generated by Chatwarden. It records what the kit held. It does not say whether any content is unlawful and is not legal advice.');
    expect(b.report).toEqual({
      id: 'r1',
      createdAt: NOW - DAY,
      roomTags: { mode: 'ranked' },
      category: 'harassment',
      reason: 'harassment',
      note: 'tarvo said it twice',
      status: 'actioned',
      decidedAt: NOW - DAY + 100,
      origin: null,
    });
    expect(b.people.map((p) => [p.index, p.ref, p.handle, p.role])).toEqual([
      [0, P.rep.id, P.rep.handle, 'reporter'],
      [1, P.tgt.id, P.tgt.handle, 'target'],
      [2, P.bys.id, P.bys.handle, 'speaker'],
    ]);
    expect(b.excerpt.map((l) => [l.p, l.raw])).toEqual([
      [0, 'tarvo please stop'],
      [1, 'zorbak you vlemmo'],
      [2, 'quissel not again'],
    ]);
    expect(b.decisions).toEqual([{ at: NOW - DAY + 100, by: 'mod_ann', outcome: 'actioned', badFaith: false }]);
    expect(b.sanctions).toEqual([
      {
        p: 1,
        kind: 'chat',
        rule: '1',
        reason: 'harassment of another player',
        startsAt: NOW - DAY + 100,
        endsAt: NOW - DAY + 100 + 3_600_000,
        refCode: 'M-GOLD1',
        by: 'mod_ann',
        revoked: null,
      },
    ]);
    expect(b.notices).toEqual([{ p: 1, kind: 'chat', createdAt: NOW - DAY + 101, ackedAt: NOW - DAY + 106, withdrawnAt: null }]);
    expect(b.appeals).toEqual([{ p: 1, status: 'upheld', createdAt: NOW - DAY + 111, decidedAt: NOW - DAY + 121, statement: 'drakkuun statement about the chat sanction' }]);
    expect(b.audit.map((a) => [a.action, a.target?.type])).toEqual([
      ['report.view', 'report'],
      ['report.decide', 'report'],
      ['sanction.revoke', 'sanction'],
    ]);
    expect(b.audit.map((a) => a.actor)).toEqual(['mod_ann', 'mod_ann', 'mod_bea']);
    expect(b.hold).toEqual({ code: 'legal_proceeding', at: NOW, releasedAt: null });
  });

  it('a report with no hold says so, an open report has no decisions, and an unknown report is not_found', async () => {
    const w = await legalWorld();
    w.store.insertReport((await import('./legalWorld.js')).storedReport('ro', NOW - DAY));
    const b = await bundleOf(w, 'ro');
    expect(b.hold).toBeNull();
    expect(b.decisions).toEqual([]);
    expect(b.sanctions).toEqual([]);
    expect(await w.cw.legal.bundle('nope', { actor: OWNER })).toEqual({ ok: false, error: 'not_found' });
  });

  it('a released hold shows when it was released; a revoked sanction shows who and when, not why', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    w.store.revokeSanctionGroup('g-r1', 'mod_bea', NOW - 5, 'private revoke reason zorbak');
    await w.cw.legal.hold('r1', { code: 'other', actor: 'senior_gus' });
    w.clock.t += 1000;
    await w.cw.legal.release('r1', { actor: OWNER });
    const b = await bundleOf(w, 'r1');
    expect(b.hold).toEqual({ code: 'other', at: NOW, releasedAt: NOW + 1000 });
    expect(b.sanctions[0]?.revoked).toEqual({ at: NOW - 5, by: 'mod_bea' });
    expect(JSON.stringify(b)).not.toContain('private revoke reason');
  });

  it('a filter report (reporter filter:<id>) has no reporter among the people and a null origin key of person', async () => {
    const w = await legalWorld();
    const { storedReport } = await import('./legalWorld.js');
    w.store.insertReport(storedReport('rf', NOW - DAY, { reporterSubject: 'filter:rf', reporterSeat: '', reporterHandle: '', note: null, origin: 'filter', originKey: 'link.unlisted', people: [P.tgt.id], excerpt: [storedReport('x', 1).excerpt[1]!].map((l) => ({ ...l, p: 0 })) }));
    const b = await bundleOf(w, 'rf');
    expect(b.people.map((p) => p.role)).toEqual(['target']);
    expect(b.report.origin).toBe('filter');
    expect(JSON.stringify(b)).not.toContain('filter:rf');
  });
});

describe('bundle: never a hash, a raw key, an address or another player\'s id outside the people index', () => {
  it('holds none of the stored hashes, keys, addresses or account ids by default, and no staff-only free text', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    const text = JSON.stringify(await bundleOf(w, 'r1'));
    for (const p of Object.values(P)) for (const secret of [p.key, p.ip, p.account]) expect(text, secret).not.toContain(secret);
    // the moderator's private note, the appeal decision reason and the notice's quoted lines are not part of a bundle
    for (const staffOnly of ['private moderator note glarn', 'private decision reason fenrisk', '2027-01-15']) expect(text, staffOnly).not.toContain(staffOnly);
    // every subject id in the file is in the people index
    const ids = new Set(text.match(/s_[a-z]+_[a-z]+/g) ?? []);
    expect([...ids].sort()).toEqual([P.bys.id, P.rep.id, P.tgt.id].sort());
  });

  it('account ids appear only with includeAccounts, and then only on the people', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    const plain = await bundleOf(w, 'r1');
    expect(plain.people.every((p) => p.accounts === undefined)).toBe(true);
    const withAccounts = await bundleOf(w, 'r1', true);
    expect(withAccounts.people.map((p) => p.accounts)).toEqual([[P.rep.account], [P.tgt.account], [P.bys.account]]);
    const text = JSON.stringify(withAccounts);
    for (const p of Object.values(P)) for (const secret of [p.key, p.ip]) expect(text, secret).not.toContain(secret);
    expect(JSON.stringify(await bundleOf(w, 'r1', false))).not.toContain(P.tgt.account);
  });

  it('appeal statements are there while the kit still holds them and gone once retention cleared them', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    expect((await bundleOf(w, 'r1')).appeals[0]?.statement).toContain('drakkuun');
    w.store.clearAppealStatements(NOW + 400 * DAY);
    expect((await bundleOf(w, 'r1')).appeals[0]?.statement).toBeNull();
    // and the row of another appeal on another group is not mixed in
    w.store.insertAppeal(appealRow('ap-other', 'g-other', 'r-other', NOW));
    expect((await bundleOf(w, 'r1')).appeals.length).toBe(1);
  });

  it('only the report\'s own audit rows and those of its sanction groups, oldest first; the audit of another report and of a person view are left out', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    seedFullReport(w, 'r2', NOW - DAY);
    const b = await bundleOf(w, 'r1');
    expect(b.audit.every((a) => a.target?.ref === 'r1' || a.target?.ref === 'g-r1')).toBe(true);
    expect(b.audit.map((a) => a.at)).toEqual([...b.audit.map((a) => a.at)].sort((x, y) => x - y));
    expect(b.audit.length).toBe(3);
  });
});

describe('bundle: integrity', () => {
  it('with a bundleSecret the hmac and the sha256 verify; the secret is not in the file', async () => {
    const w = await legalWorld({ bundleSecret: SECRET });
    seedFullReport(w, 'r1', NOW - DAY);
    const b = await bundleOf(w, 'r1');
    expect(b.integrity.algorithm).toBe('sha256');
    expect(b.integrity.canonicalization).toBe('chatwarden-json-1');
    expect(b.integrity.signedAt).toBe(NOW);
    expect(typeof b.integrity.hmacSha256).toBe('string');
    expect(verifyBundle(b, SECRET)).toEqual({ sha256: true, hmac: true });
    expect(verifyBundle(JSON.parse(JSON.stringify(b)) as EvidenceBundle, SECRET)).toEqual({ sha256: true, hmac: true });
    expect(JSON.stringify(b)).not.toContain(SECRET);
  });

  it('without a bundleSecret it is produced unsigned: hmacSha256 is null and the verifier says null', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    const b = await bundleOf(w, 'r1');
    expect(b.integrity.hmacSha256).toBeNull();
    expect(verifyBundle(b)).toEqual({ sha256: true, hmac: null });
  });

  it('one changed byte in any field fails both: a line, a person, a time, a hold code, an audit actor', async () => {
    const w = await legalWorld({ bundleSecret: SECRET });
    seedFullReport(w, 'r1', NOW - DAY);
    await w.cw.legal.hold('r1', { code: 'other', actor: 'senior_gus' });
    const b = await bundleOf(w, 'r1');
    const edits: Array<[string, (x: EvidenceBundle) => void]> = [
      ['a line', (x) => void (x.excerpt[1]!.raw = 'zorbak you vlemmO')],
      ['a handle', (x) => void (x.people[0]!.handle = 'RepHandlE')],
      ['a time', (x) => void (x.report.createdAt += 1)],
      ['a hold code', (x) => void (x.hold!.code = 'legal_proceeding')],
      ['an audit actor', (x) => void (x.audit[0]!.actor = 'mod_anN')],
      ['the note', (x) => void (x.report.note = 'tarvo said it onceX')],
      ['the disclaimer', (x) => void (x.disclaimer += ' ')],
      ['signedAt', (x) => void (x.integrity.signedAt += 1)],
    ];
    for (const [name, edit] of edits) {
      const copy = JSON.parse(JSON.stringify(b)) as EvidenceBundle;
      edit(copy);
      expect(verifyBundle(copy, SECRET), name).toEqual({ sha256: false, hmac: false });
    }
    expect(verifyBundle(b, `${SECRET}!`)).toEqual({ sha256: true, hmac: false });
  });

  it('the same world gives the same bytes twice (a golden-style check on the canonical text)', async () => {
    const w = await legalWorld({ bundleSecret: SECRET });
    seedFullReport(w, 'r1', NOW - DAY);
    const a = canonicalJson(await bundleOf(w, 'r1'));
    const b = canonicalJson(await bundleOf(w, 'r1'));
    expect(a).toBe(b);
    expect(a).not.toMatch(/\s{2,}|\n/);
  });
});

describe('the bundle is a read: it writes nothing and moves nothing', () => {
  it('leaves the store as it found it (no audit row, no hold, no change token move)', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    const before = JSON.stringify(w.store, (_k, v: unknown) => (v instanceof Map ? [...v.entries()] : v instanceof Set ? [...v.values()] : v));
    const token = w.store.changeToken();
    await bundleOf(w, 'r1', true);
    expect(JSON.stringify(w.store, (_k, v: unknown) => (v instanceof Map ? [...v.entries()] : v instanceof Set ? [...v.values()] : v))).toBe(before);
    expect(w.store.changeToken()).toBe(token);
  });

  it('a bad actor is a TypeError, not a bundle', async () => {
    const w = await legalWorld();
    seedFullReport(w, 'r1', NOW - DAY);
    await expect(w.cw.legal.bundle('r1', { actor: 'has space' })).rejects.toThrow(TypeError);
  });
});
