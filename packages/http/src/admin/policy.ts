import type { DocumentFormat } from '@chatwarden/core';
import { HttpError } from '../errors.js';
import type { RouteTable } from '../router.js';
import type { AdminContext } from './context.js';

const FORMATS: readonly DocumentFormat[] = ['markdown', 'html', 'text'];

/** The game name used in the code of conduct when the adopter gives none. */
export const DEFAULT_GAME_NAME = 'Our game';

/** What the policy documents need from the adopter. */
export interface PolicyOptions {
  /** Named in the code of conduct. Default `Our game`. */
  gameName?: string;
  /** Where a player can contest a decision (an http(s) URL; anything else is left out of the document). */
  contactUrl?: string;
}

/**
 * `GET /policy?format` (`policy.read`, audited as `policy.view`): `{ profile, rules, summary, documents: { codeOfConduct,
 * moderatorGuide, agentBrief } }`, all generated by the core from the profile and rules in force. `format` is
 * `markdown` (default), `html` or `text`; the agent brief is always plain text.
 */
export function policyRoutes(ctx: AdminContext, options: PolicyOptions = {}): RouteTable {
  const { cw } = ctx;
  const gameName = options.gameName ?? DEFAULT_GAME_NAME;
  const contact = options.contactUrl === undefined ? {} : { contactUrl: options.contactUrl };
  // Fail at start-up, not on the first request, when the game name cannot head a document (RangeError).
  cw.documents.codeOfConduct({ format: 'markdown', gameName, ...contact });
  return {
    'GET /policy': ctx.secure('policy.read', (c) => {
      const raw = c.req.query.format;
      if (raw !== undefined && !(FORMATS as readonly string[]).includes(raw)) throw new HttpError('invalid_query');
      const format = (raw ?? 'markdown') as DocumentFormat;
      const body = {
        profile: cw.profile,
        rules: cw.rules.all(),
        summary: cw.summary,
        documents: {
          codeOfConduct: cw.documents.codeOfConduct({ format, gameName, ...contact }),
          moderatorGuide: cw.documents.moderatorGuide({ format }),
          agentBrief: cw.documents.agentBrief(),
        },
      };
      c.audit('policy.view');
      return { status: 200, body };
    }),
  };
}
