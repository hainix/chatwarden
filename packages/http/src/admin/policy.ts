import { GUIDE_SECTIONS } from '@chatwarden/core';
import type { DocumentFormat, GuideSection } from '@chatwarden/core';
import { HttpError } from '../errors.js';
import type { RouteTable } from '../router.js';
import type { AdminContext } from './context.js';

const FORMATS: readonly DocumentFormat[] = ['markdown', 'html', 'text'];

/** `?omit=rules,ladder`: absent or empty is none; a name that is not a guide section (or any stray space) is 400 `invalid_query`. */
function omitted(raw: string | undefined): GuideSection[] {
  if (raw === undefined || raw === '') return [];
  const names = raw.split(',');
  if (!names.every((n) => (GUIDE_SECTIONS as readonly string[]).includes(n))) throw new HttpError('invalid_query');
  return [...new Set(names)] as GuideSection[];
}

/** The game name used in the code of conduct when the adopter gives none. */
export const DEFAULT_GAME_NAME = 'Our game';

/** What the policy documents need from the adopter. */
export interface PolicyOptions {
  /** Named in the code of conduct. Default `Our game`. */
  gameName?: string;
  /** Where a player can contest a decision (an http(s) URL; anything else is left out of the document). */
  contactUrl?: string;
}

/**
 * `GET /policy?format` (`policy.read`, audited as `policy.view`): `{ profile, rules, summary, notices: { reporterFeedback }, documents: { codeOfConduct,
 * moderatorGuide, agentBrief } }`, all generated by the core from the profile and rules in force. `format` is
 * `markdown` (default), `html` or `text`; the agent brief is always plain text. `omit` (comma-separated: `rules`, `ladder`) leaves those
 * sections out of the moderator guide only; the rules and profile in the answer are always whole. An unknown name is 400 `invalid_query`.
 * `GET /policy/rules` (scope-aware; `reports.decide`, plus `policy.read` for an unscoped caller): `{ rules }`, the same list, for a scoped moderator who acts on a case. Nothing else of the policy.
 */
export function policyRoutes(ctx: AdminContext, options: PolicyOptions = {}): RouteTable {
  const { cw } = ctx;
  const gameName = options.gameName ?? DEFAULT_GAME_NAME;
  const contact = options.contactUrl === undefined ? {} : { contactUrl: options.contactUrl };
  // Fail at start-up, not on the first request, when the game name cannot head a document (RangeError).
  cw.documents.codeOfConduct({ format: 'markdown', gameName, ...contact });
  return {
    'GET /policy': ctx.secure('policy.read', (c) => {
      const raw = c.req.query.format;
      if (raw !== undefined && !(FORMATS as readonly string[]).includes(raw)) throw new HttpError('invalid_query');
      const format = (raw ?? 'markdown') as DocumentFormat;
      const omitSections = omitted(c.req.query.omit);
      const body = {
        profile: cw.profile,
        rules: cw.rules.all(),
        summary: cw.summary,
        // Whether an upheld decision thanks the reporter (`limits.reporterFeedback`): a hub that previews the notices says so.
        notices: { reporterFeedback: cw.limits.reporterFeedback },
        documents: {
          codeOfConduct: cw.documents.codeOfConduct({ format, gameName, ...contact }),
          moderatorGuide: cw.documents.moderatorGuide({ format, ...(omitSections.length === 0 ? {} : { omitSections }) }),
          agentBrief: cw.documents.agentBrief(),
        },
      };
      c.audit('policy.view');
      return { status: 200, body };
    }),
    // The rule list alone, so a scoped moderator can act on a case (they never read the policy: it is not scope-aware). Read-only, no profile, no documents, no audit row (it holds no player data
    // and no setting's value). A caller with no scope needs `policy.read` as for `GET /policy`; a scoped one needs `reports.decide`, the permission to use the rules.
    'GET /policy/rules': ctx.secure(
      'reports.decide',
      (c) => {
        if (c.scope === undefined) c.need('policy.read');
        return { status: 200, body: { rules: cw.rules.all() } };
      },
      { scoped: true },
    ),
  };
}
