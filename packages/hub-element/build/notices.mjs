// The third-party notices the bundles carry. The list is derived from the esbuild metafile (every input that lives under a node_modules
// directory), so it is whatever the build really bundled and cannot drift from it. Each entry holds the package's own licence text,
// read from its directory; a package with no licence file fails the build, because shipping its code without the notice is the defect.
import { readdirSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export const NOTICES_FILE = 'THIRD_PARTY_NOTICES.txt';

const NODE_MODULES = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//g;

/**
 * The npm packages whose files are inside the bundles, from the esbuild metafiles of the builds.
 * @param {Array<{ inputs: Record<string, unknown> }>} metafiles
 * @param {string} root the directory the metafile paths are relative to (esbuild's absWorkingDir)
 * @returns {Array<{ name: string, version: string, license: string, homepage: string, dir: string, texts: Array<{ file: string, text: string }> }>}
 */
export function thirdPartyPackages(metafiles, root) {
  const dirs = new Map();
  for (const meta of metafiles) {
    for (const input of Object.keys(meta.inputs)) {
      const path = input.replaceAll('\\', '/');
      let last;
      for (const m of path.matchAll(NODE_MODULES)) last = m; // the innermost node_modules: a nested copy is its own package
      if (last === undefined) continue;
      const rel = path.slice(0, last.index + last[0].length - 1);
      dirs.set(last[1] + '@' + rel, { name: last[1], dir: resolve(root, rel) });
    }
  }
  const out = [];
  for (const { name, dir } of dirs.values()) {
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    const files = readdirSync(dir).filter((f) => /^(licen[sc]e|copying|notice)/i.test(f)).sort();
    const texts = files.map((file) => ({ file, text: readFileSync(join(dir, file), 'utf8').trim() }));
    if (texts.length === 0) throw new Error(`${name} is bundled but has no LICENSE file in ${dir}; its notice cannot be shipped`);
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'see the licence text';
    const homepage = pkg.homepage ?? (typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '');
    out.push({ name, version: String(pkg.version), license, homepage, dir, texts });
  }
  // The same package at two versions is two entries; sorted by name then version so the file is stable.
  return out.sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));
}

/** The text of THIRD_PARTY_NOTICES.txt. */
export function renderNotices(packages) {
  const rule = '='.repeat(78);
  const parts = [
    'THIRD-PARTY NOTICES',
    '',
    'dist/hub-element.js and dist/index.js of @chatwarden/hub-element (Apache-2.0) contain the code of the packages below,',
    'bundled into the scripts. Each is used under its own licence, reproduced here. This file is generated by the build from',
    'what the bundler actually included.',
  ];
  for (const p of packages) {
    parts.push('', rule, `${p.name} ${p.version}`, `License: ${p.license}`);
    if (p.homepage !== '') parts.push(p.homepage);
    for (const t of p.texts) parts.push('', t.text);
  }
  return parts.join('\n') + '\n';
}

